func gitOpsTestOptions(dir string) GitOpsOptions {
	return GitOpsOptions{ProjectDir: dir, Release: "sample", Namespace: "aster", ChartVersion: "0.9.0", Chart: "oci://registry.example.test/charts/aster", PlatformChart: "oci://registry.example.test/charts/aster-platform", OutputDir: "gitops"}
}

func writeGitOpsFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readGitOpsYAML(t *testing.T, path string) map[string]any {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var object map[string]any
	if err := yaml.Unmarshal(data, &object); err != nil {
		t.Fatal(err)
	}
	return object
}

func generatedApplicationValues(t *testing.T, dir string) map[string]any {
	t.Helper()
	object := readGitOpsYAML(t, filepath.Join(dir, "gitops", "application", "values-configmap.yaml"))
	data := object["data"].(map[string]any)[gitOpsValuesKey].(string)
	var values map[string]any
	if err := yaml.Unmarshal([]byte(data), &values); err != nil {
		t.Fatal(err)
	}
	return values
}

func readGitOpsTree(t *testing.T, root string) map[string][]byte {
	t.Helper()
	out := map[string][]byte{}
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil || entry.IsDir() {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		out[filepath.ToSlash(rel)] = data
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}
