func TestGitOpsValuesPreserveExactInputsAndSortedSkills(t *testing.T) {
	projectYAML := gitOpsProject + "categories:\n  - match: periodic\n    id: periodic\n    label: Periodic\n"
	prompt := "first line\n\n  indented line\nlast line\n"
	dir := t.TempDir()
	writeGitOpsFile(t, filepath.Join(dir, "project.yaml"), projectYAML)
	writeGitOpsFile(t, filepath.Join(dir, "prompts", "system.md"), prompt)
	writeGitOpsFile(t, filepath.Join(dir, "deploy", "values.yaml"), "mode: cron\nreplicaCount: 2\n")
	writeGitOpsFile(t, filepath.Join(dir, "skills", "z.yaml"), "id: z\ntriggers: [z]\nrequired_evidence:\n  - id: z\n    any_of: [z]\n")
	writeGitOpsFile(t, filepath.Join(dir, "skills", "a.yaml"), "id: a\ntriggers: [a]\nrequired_evidence:\n  - id: a\n    any_of: [a]\n")
	if err := RenderGitOps(gitOpsTestOptions(dir), nil); err != nil {
		t.Fatal(err)
	}
	values := generatedApplicationValues(t, dir)
	project := values["project"].(map[string]any)
	if project["config"] != projectYAML || project["systemPrompt"] != prompt {
		t.Fatalf("exact input did not round-trip\nconfig=%q\nprompt=%q", project["config"], project["systemPrompt"])
	}
	skills := project["skills"].(map[string]any)
	keys := make([]string, 0, len(skills))
	for key := range skills {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	if !reflect.DeepEqual(keys, []string{"a.yaml", "z.yaml"}) || values["replicaCount"] != 2 {
		t.Fatalf("generated values = %#v", values)
	}
}

func TestGitOpsDeterministicAndCheckoutIndependent(t *testing.T) {
	dirA := writeGitOpsConsumer(t, "mode: cron\n", "", nil)
	dirB := writeGitOpsConsumer(t, "mode: cron\n", "", nil)
	if err := RenderGitOps(gitOpsTestOptions(dirA), nil); err != nil {
		t.Fatal(err)
	}
	if err := RenderGitOps(gitOpsTestOptions(dirB), nil); err != nil {
		t.Fatal(err)
	}
	filesA, filesB := readGitOpsTree(t, filepath.Join(dirA, "gitops")), readGitOpsTree(t, filepath.Join(dirB, "gitops"))
	if !reflect.DeepEqual(filesA, filesB) {
		t.Fatal("generated output depends on checkout path")
	}
	if err := RenderGitOps(gitOpsTestOptions(dirA), nil); err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(filesA, readGitOpsTree(t, filepath.Join(dirA, "gitops"))) {
		t.Fatal("second render changed output")
	}
	for name, data := range filesA {
		lower := bytes.ToLower(data)
		if bytes.Contains(data, []byte(dirA)) || bytes.Contains(lower, []byte("capz")) || bytes.Contains(lower, []byte("azure")) {
			t.Errorf("%s contains local or project-specific text", name)
		}
	}
}

