func TestRenderAndCheckGitOpsApplicationOnly(t *testing.T) {
	dir := writeGitOpsConsumer(t, "mode: cron\n", "", nil)
	opts := gitOpsTestOptions(dir)
	var output bytes.Buffer
	if err := RenderGitOps(opts, &output); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"README.md", "kustomization.yaml", "sources/kustomization.yaml", "sources/application-chart.yaml", "application/namespace.yaml", "application/values-configmap.yaml", "application/helmrelease.yaml", "application/kustomization.yaml"} {
		if _, err := os.Stat(filepath.Join(dir, "gitops", filepath.FromSlash(name))); err != nil {
			t.Errorf("missing %s: %v", name, err)
		}
	}
	if _, err := os.Stat(filepath.Join(dir, "gitops", "platform", "helmrelease.yaml")); !os.IsNotExist(err) {
		t.Fatalf("application-only render created platform HelmRelease: %v", err)
	}
	application := readGitOpsYAML(t, filepath.Join(dir, "gitops", "application", "helmrelease.yaml"))
	spec := application["spec"].(map[string]any)
	if _, ok := spec["dependsOn"]; ok {
		t.Fatal("application-only HelmRelease has dependsOn")
	}
	if spec["targetNamespace"] != "aster" || spec["timeout"] != "15m" {
		t.Fatalf("unexpected HelmRelease contract: %#v", spec)
	}
	if err := CheckGitOps(opts, &output); err != nil {
		t.Fatal(err)
	}
	readme, err := os.ReadFile(filepath.Join(dir, "gitops", "README.md"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"generated by Aster", "ConfigMaps contain project", "no Secret values", "reverting and merging"} {
		if !bytes.Contains(readme, []byte(want)) {
			t.Errorf("README missing %q", want)
		}
	}
}

