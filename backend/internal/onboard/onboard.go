// buildScaffoldData assembles template input from options and categories.
func buildScaffoldData(opts Options, cats []project.CategoryRule) scaffoldData {
	owner, name := splitRepo(opts.DashboardRepo)
	srcOwner, srcName := splitRepo(opts.SourceRepo)
	mode := opts.Mode
	if mode == "" {
		mode = modePages
	}
	aiEnabled := effectiveAIEnabled(opts)
	aiAPI := deploymentAIAPI(opts)
	if aiAPI == "" || opts.deferDeploymentAI {
		aiAPI = project.AIAPIChatCompletions
	}
	aiEndpoint := deploymentAIEndpoint(opts)
	if aiEndpoint == "" || opts.deferDeploymentAI {
		if aiAPI == project.AIAPIResponses {
			aiEndpoint = "http://<your-model-svc>.<ns>.svc.cluster.local:8000/v1/responses"
		} else {
			aiEndpoint = "http://<your-model-svc>.<ns>.svc.cluster.local:8000/v1/chat/completions"
		}
	}
	aiModel := deploymentAIModel(opts)
	if aiModel == "" || opts.deferDeploymentAI {
		aiModel = "<your-model-id>"
	}
	d := scaffoldData{
		ID:                derivedID(opts),
		Name:              derivedName(opts),
		ShortName:         opts.ShortName,
		Provider:          provider(opts),
		Bucket:            bucket(opts),
		GCSWebBase:        opts.GCSWebBase,
		ExactJobs:         append([]string(nil), opts.ExactJobs...),
		Title:             derivedName(opts) + " Prow Dashboard",
		BasePath:          "/" + name,
		SiteURL:           "https://" + owner + ".github.io/" + name,
		SourceOwner:       srcOwner,
		SourceName:        srcName,
		Categories:        cats,
		IncludePresubmits: includePresubmits(opts),
		EngineRef:         opts.EngineRef,
		Mode:              mode,
		AIEnabled:         aiEnabled,
		AIAPI:             aiAPI,
		AIEndpoint:        aiEndpoint,
		AIModel:           aiModel,
		K8sStorageClass:   opts.K8sStorageClass,
		K8sExistingClaim:  opts.K8sExistingClaim,
		Namespace:         k8sName(derivedID(opts)),
		DashboardName:     name,
	}
	// Kubernetes-native serves at the domain root from the in-cluster server, so
	// there is no gh-pages subpath; site_url is a placeholder until an ingress
	// hostname exists.
	if mode == modeK8s {
		d.BasePath = "/"
		d.SiteURL = "http://localhost:8080"
	}
	if opts.TestGrid != "" {
		d.DiscoveryTestGrid = opts.TestGrid
	} else {
		d.BucketDiscovery = true
	}
	return d
}

