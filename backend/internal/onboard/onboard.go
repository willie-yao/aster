// k8sCILogsBucket is the default artifact bucket for Kubernetes TestGrid jobs.
const k8sCILogsBucket = "kubernetes-ci-logs"

// Deploy modes the scaffold targets.
const (
	modePages = "pages"
	modeK8s   = "k8s"
)

// Run produces a scaffold for a new dashboard. It verifies discovery, infers
// categories, renders files, validates project.yaml, and emits the scaffold.
// It performs no secret writes.
func Run(ctx context.Context, opts Options) error {
	if err := validateOptions(&opts); err != nil {
		return err
	}

	// Sweep with a minimal config to confirm discovery finds jobs.
	sweepCfg := sweepConfig(opts)
	jobs, err := discover(ctx, sweepCfg, opts.IncludePresubmits)
	if err != nil {
		return fmt.Errorf("job sweep: %w", err)
	}
	if len(jobs) == 0 {
		return fmt.Errorf("discovery found 0 jobs for the given input; check the testgrid dashboard name or bucket before scaffolding")
	}
	jobNames := make([]string, 0, len(jobs))
	for _, j := range jobs {
		jobNames = append(jobNames, j.Name)
	}
	sort.Strings(jobNames)
	fmt.Printf("✓ discovery found %d jobs\n", len(jobNames))

	// Generate deterministic files from the discovered jobs.
	cats := InferCategories(jobNames)
	data := buildScaffoldData(opts, cats)

	projectYAML, err := renderProjectYAML(data)
	if err != nil {
		return fmt.Errorf("rendering project.yaml: %w", err)
	}

	// Validate generated YAML through the real loader before writing it.
	if err := validateGeneratedYAML(projectYAML); err != nil {
		return fmt.Errorf("generated project.yaml failed validation: %w", err)
	}

	// Render the remaining scaffold files. The deploy files differ by mode; the
	// prompt is the same either way.
	files := map[string]string{"project.yaml": projectYAML}
	dashOwner, dashName := splitRepo(opts.DashboardRepo)
	switch opts.Mode {
	case modeK8s:
		if files["deploy/values.yaml"], err = render(k8sValuesTmpl, data); err != nil {
			return err
		}
		if files["deploy/README.md"], err = render(k8sDeployReadmeTmpl, data); err != nil {
			return err
		}
	default:
		if files[".github/workflows/deploy.yml"], err = render(deployYAMLTmpl, data); err != nil {
			return err
		}
		if files["CHECKLIST.md"], err = render(checklistTmpl, checklistData{
			Name: data.Name, DashboardOwner: dashOwner, DashboardName: dashName, EngineRef: data.EngineRef,
		}); err != nil {
			return err
		}
	}
	files["prompts/system.md"], err = buildSystemPrompt(ctx, opts, data)
	if err != nil {
		return err
	}

	// Open a PR against the dashboard repo, or write a local scaffold.
	if opts.OpenPR {
		title := fmt.Sprintf("Add %s prow-ai-dashboard scaffold", data.Name)
		httpClient := &http.Client{Timeout: 30 * time.Second}
		fmt.Printf("⤴ opening a scaffold PR against %s…\n", opts.DashboardRepo)
		url, err := ghpr.NewClient(httpClient, opts.GitHubToken).OpenPR(ctx, ghpr.Request{
			Owner:        dashOwner,
			Repo:         dashName,
			Files:        files,
			BranchPrefix: "onboard/scaffold",
			Title:        title,
			Body:         scaffoldPRBody(data.Name, opts.Mode),
		})
		if err != nil {
			return fmt.Errorf("opening scaffold PR: %w", err)
		}
		fmt.Printf("\n✓ opened scaffold PR: %s\n", url)
		fmt.Printf("  review it (especially prompts/system.md), then follow %s\n", scaffoldGuide(opts.Mode))
		return nil
	}

	if err := writeFiles(opts.OutDir, files); err != nil {
		return err
	}
	fmt.Printf("\n✓ scaffold written to %s/\n", opts.OutDir)
	fmt.Printf("  next: review prompts/system.md and project.yaml, then follow %s\n", scaffoldGuide(opts.Mode))
	if len(cats) > 0 {
		fmt.Printf("  inferred %d categor%s from job names (review/reorder them)\n", len(cats), plural(len(cats)))
	}
	return nil
}

func scaffoldGuide(mode string) string {
	if mode == modeK8s {
		return "deploy/README.md"
	}
	return "CHECKLIST.md"
}

// scaffoldPRBody is the PR description: a short summary plus the human steps.
func scaffoldPRBody(name, mode string) string {
	guide := "`" + scaffoldGuide(mode) + "`"
	finalStep := "Complete the GitHub configuration in `CHECKLIST.md` (enable Pages, set the AI provider variables and token)."
	if mode == modeK8s {
		finalStep = "Fill in `deploy/values.yaml`, then follow `deploy/README.md` to install the dashboard with Helm."
	}
	return fmt.Sprintf("Generated by `prow-ai-dashboard onboard` for **%s**. The job sweep confirmed discovery finds jobs.\n\n"+
		"**Before merging or deploying:**\n"+
		"- Review and fill in `prompts/system.md`.\n"+
		"- Review or trim the inferred `categories` in `project.yaml`.\n"+
		"- %s\n\n"+
		"See %s for the full steps.", name, finalStep, guide)
}

// buildSystemPrompt drafts prompts/system.md from source docs when AI is
// available. It falls back to the stub on disabled, missing, slow, or failed AI.
func buildSystemPrompt(ctx context.Context, opts Options, data scaffoldData) (string, error) {
	if opts.NoPrompt || opts.AIToken == "" {
		if opts.AIToken == "" && !opts.NoPrompt {
			fmt.Println("ⓘ no AI token (set AI_TOKEN); writing a prompts/system.md stub to fill in")
		}
		return render(systemPromptTmpl, data)
	}

	// Bound the whole drafting phase so a hung endpoint degrades to the stub
	// instead of hanging the command.
	ctx, cancel := context.WithTimeout(ctx, promptDraftTimeout)
	defer cancel()

	srcOwner, srcName := splitRepo(opts.SourceRepo)
	httpClient := &http.Client{Timeout: 30 * time.Second}

	fmt.Printf("✦ drafting prompts/system.md from %s/%s docs…\n", srcOwner, srcName)
	// Empty GitHub token means anonymous public reads.
	docs, err := fetchSourceDocs(ctx, httpClient, srcOwner, srcName, opts.GitHubToken)
	if err != nil {
		fmt.Printf("  ⚠ could not read source-repo docs (%v); writing the stub instead\n", err)
		return render(systemPromptTmpl, data)
	}

	client := ai.NewClientWithOptions(ai.Options{
		Token:    opts.AIToken,
		Endpoint: opts.AIEndpoint,
		Model:    opts.AIModel,
	})
	body, err := generatePromptBody(ctx, client, data.Name, docs)
	if err != nil {
		fmt.Printf("  ⚠ prompt generation failed (%v); writing the stub instead\n", err)
		return render(systemPromptTmpl, data)
	}
	fmt.Printf("  ✓ drafted from %d doc(s)\n", len(docs))
	return composeGeneratedPrompt(data.Name, body), nil
}

// promptDraftTimeout bounds doc fetch and one generation call.
const promptDraftTimeout = 3 * time.Minute

func validateOptions(opts *Options) error {
	if (opts.TestGrid == "") == (opts.Bucket == "") {
		return fmt.Errorf("provide exactly one of --testgrid or --bucket")
	}
	if _, _, err := parseRepo(opts.DashboardRepo); err != nil {
		return fmt.Errorf("--dashboard-repo %w", err)
	}
	if _, _, err := parseRepo(opts.SourceRepo); err != nil {
		return fmt.Errorf("--source-repo %w", err)
	}
	if opts.GCSWebBase != "" && opts.Bucket == "" {
		return fmt.Errorf("--gcsweb-base only applies with --bucket")
	}
	if opts.OpenPR && opts.GitHubToken == "" {
		return fmt.Errorf("--open-pr needs a GitHub token with write access to the dashboard repo (set GITHUB_TOKEN)")
	}
	// AI drafting needs an explicit endpoint and model because the engine has no
	// default provider. Without AI, the stub is written.
	if opts.AIToken != "" && !opts.NoPrompt {
		if opts.AIEndpoint == "" || opts.AIModel == "" {
			return fmt.Errorf("AI drafting needs AI_ENDPOINT and AI_MODEL set (your provider's chat-completions URL and model id); set both, or unset AI_TOKEN / pass --no-prompt to write the prompts/system.md stub instead")
		}
	}
	if opts.EngineRef == "" {
		opts.EngineRef = "main"
	}
	switch opts.Mode {
	case "":
		opts.Mode = modePages
	case modePages, modeK8s:
	default:
		return fmt.Errorf("--mode must be %q or %q, got %q", modePages, modeK8s, opts.Mode)
	}
	if opts.OutDir == "" {
		_, name, _ := parseRepo(opts.DashboardRepo)
		opts.OutDir = name
	}
	return nil
}

// sweepConfig builds the minimal in-memory config needed to run discovery.
func sweepConfig(opts Options) *project.Config {
	cfg := &project.Config{
		ID:      derivedID(opts),
		Name:    derivedName(opts),
		Storage: project.Storage{Provider: provider(opts), Bucket: bucket(opts), Base: opts.GCSWebBase},
	}
	if opts.TestGrid != "" {
		cfg.TestGrid = project.TestGrid{Dashboard: opts.TestGrid}
	} else {
		cfg.Discovery = project.Discovery{Source: project.DiscoveryBucket}
	}
	return cfg
}

// discover runs the same job discovery the fetcher uses, by source.
func discover(ctx context.Context, cfg *project.Config, includePresubmits bool) ([]models.ProwJob, error) {
	client := &http.Client{Timeout: 30 * time.Second}
	if cfg.EffectiveDiscoverySource() == project.DiscoveryBucket {
		backend, err := storage.New(cfg.StorageConfig(), client)
		if err != nil {
			return nil, fmt.Errorf("configuring storage: %w", err)
		}
		return prowbuild.DiscoverJobs(ctx, backend, includePresubmits, cfg.Discovery.JobFilters)
	}
	jobs, err := jobconfig.FetchJobConfigs(ctx, client, cfg)
	if err != nil {
		return nil, err
	}
	if includePresubmits {
		return jobs, nil
	}
	periodic := jobs[:0]
	for _, j := range jobs {
		if j.JobType == models.JobTypePeriodic {
			periodic = append(periodic, j)
		}
	}
	return periodic, nil
}

// buildScaffoldData assembles template input from options and categories.
func buildScaffoldData(opts Options, cats []project.CategoryRule) scaffoldData {
	owner, name := splitRepo(opts.DashboardRepo)
	srcOwner, srcName := splitRepo(opts.SourceRepo)
	mode := opts.Mode
	if mode == "" {
		mode = modePages
	}
	d := scaffoldData{
		ID:                derivedID(opts),
		Name:              derivedName(opts),
		Provider:          provider(opts),
		Bucket:            bucket(opts),
		GCSWebBase:        opts.GCSWebBase,
		Title:             derivedName(opts) + " Prow Dashboard",
		BasePath:          "/" + name,
		SiteURL:           "https://" + owner + ".github.io/" + name,
		SourceOwner:       srcOwner,
		SourceName:        srcName,
		Categories:        cats,
		IncludePresubmits: opts.IncludePresubmits,
		EngineRef:         opts.EngineRef,
		Mode:              mode,
		AIEndpoint:        opts.AIEndpoint,
		AIModel:           opts.AIModel,
		Namespace:         k8sName(derivedID(opts)),
		DashboardName:     name,
	}
	// Kubernetes-native serves at the domain root from the in-cluster server, so
	// there is no gh-pages subpath; site_url is a placeholder until an ingress
	// hostname exists.
	if mode == modeK8s {
		d.BasePath = "/"
		d.SiteURL = "http://localhost:8080"
	}
	if opts.TestGrid != "" {
		d.DiscoveryTestGrid = opts.TestGrid
	} else {
		d.BucketDiscovery = true
	}
	return d
}

func validateGeneratedYAML(yamlText string) error {
	dir, err := os.MkdirTemp("", "onboard-validate-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(dir)
	path := filepath.Join(dir, "project.yaml")
	if err := os.WriteFile(path, []byte(yamlText), 0o644); err != nil {
		return err
	}
	_, err = project.Load(path)
	return err
}

func writeFiles(outDir string, files map[string]string) error {
	// Never silently clobber an existing scaffold or repo.
	for rel := range files {
		full := filepath.Join(outDir, rel)
		if _, err := os.Stat(full); err == nil {
			return fmt.Errorf("refusing to overwrite existing %s; choose an empty --out directory", full)
		} else if !os.IsNotExist(err) {
			return fmt.Errorf("checking %s: %w", full, err)
		}
	}
	for rel, content := range files {
		full := filepath.Join(outDir, rel)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", rel, err)
		}
	}
	return nil
}

func provider(opts Options) string {
	if opts.GCSWebBase != "" {
		return string(storage.ProviderGCSWeb)
	}
	return string(storage.ProviderGCS)
}

func bucket(opts Options) string {
	if opts.Bucket != "" {
		return opts.Bucket
	}
	return k8sCILogsBucket
}

func derivedID(opts Options) string {
	if opts.ID != "" {
		return opts.ID
	}
	_, name := splitRepo(opts.DashboardRepo)
	// Strip a trailing dashboard suffix so the id reads like the project.
	id := strings.TrimSuffix(name, "-prow-ai-dashboard")
	id = strings.TrimSuffix(id, "-prow-dashboard")
	if id == "" {
		id = name
	}
	return id
}

func derivedName(opts Options) string {
	if opts.Name != "" {
		return opts.Name
	}
	return labelFor(derivedID(opts))
}

// k8sName coerces s into a DNS-1123 label safe for a namespace and Helm release
// name: lowercase, non-alphanumerics to '-', collapsed, trimmed, capped at 63.
func k8sName(s string) string {
	var b strings.Builder
	prevDash := false
	for _, r := range strings.ToLower(s) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			b.WriteRune(r)
			prevDash = false
			continue
		}
		if !prevDash {
			b.WriteByte('-')
			prevDash = true
		}
	}
	out := strings.Trim(b.String(), "-")
	if len(out) > 63 {
		out = strings.Trim(out[:63], "-")
	}
	if out == "" {
		out = "dashboard"
	}
	return out
}

func splitRepo(repo string) (owner, name string) {
	owner, name, _ = parseRepo(repo)
	return owner, name
}

// parseRepo strictly parses owner/name with one slash and non-empty parts.
func parseRepo(repo string) (owner, name string, err error) {
	parts := strings.Split(repo, "/")
	if len(parts) != 2 || parts[0] == "" || parts[1] == "" {
		return "", "", fmt.Errorf("must be owner/name, got %q", repo)
	}
	return parts[0], parts[1], nil
}

func render(t *template.Template, data any) (string, error) {
	var b strings.Builder
	if err := t.Execute(&b, data); err != nil {
		return "", err
	}
	return b.String(), nil
}

func plural(n int) string {
	if n == 1 {
		return "y"
	}
	return "ies"
}
